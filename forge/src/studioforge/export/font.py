def text_strokes(text: str, x: float, y: float, height: float = 1.0, rot: float = 0.0, anchor: str = "center"):
    """Polylines (list of [(x,y)...]) in board coords (y down) for `text` centred at (x, y)."""
    import math
    adv = 0.85 * height * 0.6 / 0.6 * 0.75
    scale = height
    width = max(0, len(text) - 1) * adv + 0.6 * scale
    ox = -width / 2 if anchor == "center" else 0.0
    oy = height / 2
    a = math.radians(rot)
    ca, sa = math.cos(a), math.sin(a)
    out = []
    for i, ch in enumerate(text.upper() if text else ""):
        glyph = _G.get(ch)
        if glyph is None:
            glyph = _G.get(ch.upper(), [])
        for stroke in glyph:
            pts = []
            for (gx, gy) in stroke:
                px = ox + i * adv + gx * scale
                py = oy - gy * scale             # y down
                rx = px * ca + py * sa
                ry = -px * sa + py * ca
                pts.append((x + rx, y + ry))
            out.append(pts)
    return out
